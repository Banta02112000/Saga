# Builds web/shared/i18n-it.js from scripts/it_dict.py ("#" in a key stands for any number).
import sys, json, re, os
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here)
import it_dict
plain, pats = {}, []
for k, v in it_dict.D.items():
    if '#' in k:
        rx = re.escape(k).replace('\\#', '(\\d[\\d,.]*)').replace('#', '(\\d[\\d,.]*)')
        i = 1
        while '#' in v: v = v.replace('#', '$%d' % i, 1); i += 1
        pats.append((rx, v))
    else: plain[k.strip()] = v
pats += it_dict.P
out = os.path.join(here, '..', 'web', 'shared', 'i18n-it.js')
open(out, 'w').write("/* Italian strings for every tab (generated by scripts/gen_it.py from scripts/it_dict.py). */\nwindow.BANTA_IT = " + json.dumps(plain, ensure_ascii=False, indent=0) + ";\nwindow.BANTA_IT_PAT = " + json.dumps(pats, ensure_ascii=False, indent=0) + ";\n")
print(len(plain), 'strings,', len(pats), 'patterns')
